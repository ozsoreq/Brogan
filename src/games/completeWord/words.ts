// Common short words that aren't in the bank but could still be formed by
// swapping one letter of a bank word (e.g. דג -> גג / חג). A distractor that
// spells any real word would make a round genuinely ambiguous.
const OTHER_REAL_WORDS = new Set(
  (
    'גג חג תג דג אב אם בן בת גן כן לא יש שם זה זו הם הן אז גם עם על אל כל מי מה פה שן ' +
    'רע טוב חם קר רך גב לב יד אף עט סל חד צד קו גל חול טל רץ שר טס עף בא בו בה לו לה ' +
    'דב דם דף בד בר בור בית בוא גור גיל דור דיו זר חור חוט חיה טיל כד כר לח מר נר סיר ' +
    'עיר עור פר צב קיר קול קום ריב רב רוח שיר שיח שק תור תות תוף'
  ).split(' '),
)

// Hebrew final-form letters and punctuation never appear as a blank since
// they aren't in HEBREW_ALPHABET; any other position may be hidden.
function blankCandidates(word: string): number[] {
  return [...word].flatMap((ch, i) => (HEBREW_ALPHABET.includes(ch) ? [i] : []))
}

function shuffle<T>(items: T[]): T[] {
  const arr = [...items]
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[arr[i], arr[j]] = [arr[j], arr[i]]
  }
  return arr
}

const WORD_BANK: WordEntry[] = Array.from(
  new Map(RAW_WORDS.map(([word, emoji]) => [word, { word, emoji }])).values(),
).filter((entry) => blankCandidates(entry.word).length > 0)

const KNOWN_WORDS = new Set([...WORD_BANK.map((e) => e.word), ...OTHER_REAL_WORDS])

const ROUNDS_PER_GAME = 10
const OPTIONS_PER_ROUND = 10

function formsOtherWord(word: string, blankIndex: number, letter: string): boolean {
  const candidate = word.slice(0, blankIndex) + letter + word.slice(blankIndex + 1)
  return candidate !== word && KNOWN_WORDS.has(candidate)
}

export function buildOptions(word: string, blankIndex: number): string[] {
  const correctLetter = word[blankIndex]
  const distractorPool = HEBREW_ALPHABET.filter(
    (letter) => letter !== correctLetter && !formsOtherWord(word, blankIndex, letter),
  )
  const distractors = shuffle(distractorPool).slice(0, OPTIONS_PER_ROUND - 1)
  return shuffle([correctLetter, ...distractors])
}

export function buildRounds(): Round[] {
  return shuffle(WORD_BANK)
    .slice(0, ROUNDS_PER_GAME)
    .map((entry) => {
      const candidates = blankCandidates(entry.word)
      const blankIndex = candidates[Math.floor(Math.random() * candidates.length)]
      return {
        word: entry.word,
        emoji: entry.emoji,
        blankIndex,
        correctLetter: entry.word[blankIndex],
        options: buildOptions(entry.word, blankIndex),
      }
    })
}

