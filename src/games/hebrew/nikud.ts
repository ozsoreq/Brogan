const MARKS = /[֑-ֽֿ-ׇׂׅׄ]/g

export function stripNikud(text: string) {
  return text.replace(MARKS, '')
}

/** The text to show: vocalized when nikud is on and a version exists. */
export function display(text: string, withNikud: boolean) {
  return withNikud ? (NIKUD[text] ?? text) : text
}
