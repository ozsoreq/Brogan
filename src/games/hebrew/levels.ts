export const TOTAL_LEVELS = 50

export interface StoryQuestion {
  prompt: string
  correctAnswer: string
  distractors: string[]
}

export interface StoryLevel {
  title: string
  story: string
  questions: StoryQuestion[]
}

function shuffle<T>(items: T[]): T[] {
  const arr = [...items]
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[arr[i], arr[j]] = [arr[j], arr[i]]
  }
  return arr
}

export interface BuiltQuestion {
  prompt: string
  options: string[]
  correctIndex: number
}

export interface BuiltLevel {
  title: string
  story: string
  questions: BuiltQuestion[]
}

export function buildLevel(level: number): BuiltLevel {
  const source = STORY_LEVELS[level - 1]
  return {
    title: source.title,
    story: source.story,
    questions: source.questions.map((q) => {
      const options = shuffle([q.correctAnswer, ...q.distractors])
      return { prompt: q.prompt, options, correctIndex: options.indexOf(q.correctAnswer) }
    }),
  }
}

